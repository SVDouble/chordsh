/** Learn transposition-invariant root transitions from the tune split only. */
import { it } from 'vitest';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { corpora, loadPiece, pieceIds, split } from './eval/truth';
import { mod12 } from '../src/theory/pitch';
import { keyEq } from '../src/theory/scales';

it('train harmonic transitions on the tune split', () => {
  const manifest = fs.readFileSync('scripts/datasets.json', 'utf8');
  const expected = JSON.parse(manifest)
    .corpora.map((c: { name: string }) => c.name)
    .sort();
  if (JSON.stringify(corpora()) !== JSON.stringify(expected)) throw new Error('Run npm run fetch-data first.');
  const counts = Array.from({ length: 2 }, () => Array.from({ length: 12 }, () => Array<number>(12).fill(1)));
  const training: { corpus: string; pieces: number; transitions: number }[] = [];
  for (const corpus of expected as string[]) {
    const ids = pieceIds(corpus).filter((id) => split(corpus, id) === 'tune');
    const transitions: [number, number, number][] = [];
    for (const id of ids) {
      const chords = loadPiece(corpus, id).chords;
      for (let i = 1; i < chords.length; i++) {
        const a = chords[i - 1],
          b = chords[i];
        if (!a.key || !b.key || !keyEq(a.key, b.key) || a.t1 < b.t0) continue;
        if (a.root === b.root && a.family === b.family) continue;
        transitions.push([b.key.mode === 'major' ? 0 : 1, mod12(a.root - b.key.tonic), mod12(b.root - b.key.tonic)]);
      }
    }
    if (!transitions.length) throw new Error(`No tune transitions in ${corpus}.`);
    // Equal total weight per corpus keeps the much larger jazz collection from dominating.
    for (const [mode, from, to] of transitions) counts[mode][from][to] += 1000 / transitions.length;
    training.push({ corpus, pieces: ids.length, transitions: transitions.length });
  }
  const probabilities = counts.map((mode) =>
    mode.map((row) => {
      const sum = row.reduce((a, b) => a + b, 0);
      return row.map((n) => Number((n / sum).toPrecision(10)));
    }),
  );
  const model = {
    version: 1,
    split: 'tune',
    manifestSha256: createHash('sha256').update(manifest).digest('hex'),
    training,
    probabilities,
  };
  fs.writeFileSync(
    'src/engine/transitions.ts',
    `// Generated by npm run train from tune annotations only. Do not edit by hand.\nexport const TRANSITIONS = ${JSON.stringify(model, null, 2)} as const;\n`,
  );
  console.log(training);
});
