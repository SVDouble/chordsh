import { it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import type { PredictionModel } from '../src/engine/prediction';
import { predictionExamples } from './eval/prediction';
import { DATA, corpora, loadPiece, pieceIds, split } from './eval/truth';

it('train continuation model using tune annotations only', () => {
  const manifest = fs.readFileSync('scripts/datasets.json', 'utf8');
  const expected: string[] = JSON.parse(manifest)
    .corpora.map((c: { name: string }) => c.name)
    .sort();
  if (JSON.stringify(expected) !== JSON.stringify(corpora())) throw new Error('Run npm run fetch-data first.');
  const hash = createHash('sha256');
  const model: PredictionModel = {
    version: 1,
    split: 'tune',
    manifestSha256: createHash('sha256').update(manifest).digest('hex'),
    dataSha256: '',
    training: [],
    unigram: [Array<number>(60).fill(0), Array<number>(60).fill(0)],
    single: {},
    pair: {},
  };
  const pairs = new Map<string, Map<number, number>>();
  for (const corpus of expected) {
    const tuneIds = pieceIds(corpus).filter((id) => split(corpus, id) === 'tune');
    const ids = process.env.VALIDATE ? tuneIds.slice(0, Math.floor(tuneIds.length * 0.8)) : tuneIds;
    const examples = ids.flatMap((id) => {
      hash.update(`${corpus}/${id}\0`).update(fs.readFileSync(path.join(DATA, corpus, `${id}.json`)));
      return predictionExamples(loadPiece(corpus, id));
    });
    if (!examples.length) throw new Error(`No transitions for ${corpus}.`);
    const weight = 1000 / examples.length;
    for (const { key, history, next } of examples) {
      const mode = key.mode === 'major' ? 0 : 1;
      const current = history.at(-1)!;
      model.unigram[mode][next] += weight;
      const singleId = `${mode}:${current}`;
      model.single[singleId] ??= Array<number>(60).fill(0);
      model.single[singleId][next] += weight;
      if (history.length > 1) {
        const id = `${mode}:${history.at(-2)}:${current}`;
        const row = pairs.get(id) ?? new Map<number, number>();
        row.set(next, (row.get(next) ?? 0) + weight);
        pairs.set(id, row);
      }
    }
    model.training.push({ corpus, pieces: ids.length, transitions: examples.length });
  }
  const round = (value: number) => Number(value.toPrecision(7));
  model.unigram = model.unigram.map((row) => row.map(round));
  for (const [id, row] of Object.entries(model.single)) model.single[id] = row.map(round);
  model.pair = Object.fromEntries(
    [...pairs]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([id, row]) => [id, [...row].sort(([a], [b]) => a - b).map(([to, count]) => [to, round(count)])]),
  );
  model.dataSha256 = hash.digest('hex');
  if (process.env.VALIDATE) fs.writeFileSync('local/prediction-validation-model.json', JSON.stringify(model));
  else
    fs.writeFileSync(
      'src/engine/predictionModel.ts',
      `// Generated by npm run train:prediction from tune annotations only.\n// biome-ignore-all lint/suspicious/noApproximativeNumericConstant: Learned counts are data, not mathematical constants.\nimport type { PredictionModel } from './prediction';\nexport const PREDICTION_MODEL: PredictionModel = ${JSON.stringify(model)};\n`,
    );
  console.log(model.training, `${pairs.size} two-chord contexts`);
});
